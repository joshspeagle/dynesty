# default span: the 5-sigma credible interval
_SPAN_5SIGMA = 0.999999426697


def _make_subplots(fig, nx, ny, xsize, ysize):
    # Setting up default plot layout.
    if fig is None:
        fig, axes = pl.subplots(nx, ny, figsize=(xsize, ysize))
        axes = np.asarray(axes).reshape(nx, ny)
    else:
        fig, axes = fig
        try:
            axes = np.asarray(axes).reshape(nx, ny)
        except ValueError:
            raise ValueError("Provided axes do not match the required shape")
    return fig, axes


def rotate_ticks(ax, xy):
    if xy == 'x':
        labs = ax.get_xticklabels()
    else:
        labs = ax.get_yticklabels()
    for lab in labs:
        lab.set_rotation(45)


def plot_thruth(ax,
                truths,
                truth_color,
                truth_kwargs,
                vertical=None,
                horizontal=None):
    """
Plot the truth line (horizontal or vertical).
truths can be None or one value or a list
"""
    if vertical:
        func = ax.axvline
    elif horizontal:
        func = ax.axhline
    else:
        raise ValueError('vertical or horizontal option must be specified')
    if truths is not None:
        try:
            curt = iter(truths)
        except TypeError:
            curt = [truths]
        for t in curt:
            func(t, color=truth_color, **truth_kwargs)


def check_span(span, samples, weights):
    """
If span is a list of scalars, replace it by the list of bounds.
If the input is list of pairs, it is kept intact
    """
    for i, cur in enumerate(span):
        if np.iterable(cur):
            if len(cur) != 2:
                raise ValueError('Incorrect span value')
        else:
            q = [0.5 - 0.5 * cur, 0.5 + 0.5 * cur]
            span[i] = _quantile(samples[i], q, weights=weights)


def check_span_pairs(span):
    """
Check that each element of span is a (lower, upper) pair
    """
    for cur in span:
        if np.shape(cur) != (2, ):
            raise ValueError('Each element of span must be a '
                             f'(lower, upper) pair, got {cur}')


def _with_defaults(kwargs, **defaults):
    """
Return a copy of the kwargs dictionary (which can be None)
with the missing keys taken from defaults
    """
    return {**defaults, **(kwargs or {})}


def _xlabel(i):
    """
Default label of the i-th (zero-based) parameter
    """
    return f"$x_{{{i + 1}}}$"


def _locator(max_n_ticks, prune=None):
    """
Tick locator with at most max_n_ticks ticks (no ticks if max_n_ticks==0)
    """
    if max_n_ticks == 0:
        return NullLocator()
    return MaxNLocator(max_n_ticks, prune=prune)


def _formatter(use_math_text):
    return ScalarFormatter(useMathText=use_math_text)


def _prepare_samples(samples, weights, dims):
    """
Convert samples into an (ndim, nsamps) array, keeping only the dimensions
dims (if specified) and check that the weights are consistent with them.
A number of extra checks are here in case users are trying to plot
other results besides the `Results` instance generated by `dynesty`.
    """
    samples = np.atleast_1d(samples)
    if samples.ndim == 1:
        samples = np.atleast_2d(samples)
    else:
        assert samples.ndim == 2, "Samples must be 1- or 2-D."
        samples = samples.T
    assert samples.shape[0] <= samples.shape[1], "There are more " \
                                                 "dimensions than samples!"
    if dims is not None:
        samples = samples[dims]
    if weights.ndim != 1:
        raise ValueError("Weights must be 1-D.")
    if samples.shape[1] != weights.shape[0]:
        raise ValueError("The number of weights and samples disagree!")
    return samples


def _kde_weights(logvol, weights, nkde, rstate):
    """
Smooth the importance weights as a function of ln(volume) using
a kernel density estimate evaluated on a grid of nkde points
    """
    wt_kde = gaussian_kde(resample_equal(-logvol, weights, rstate=rstate))
    logvol_grid = np.linspace(logvol[0], logvol[-1], nkde)
    return np.interp(-logvol, -logvol_grid, wt_kde.pdf(-logvol_grid))


def _plot_quantiles(ax, x, weights, quantiles, color, label, verbose):
    """
Mark the weighted quantiles of x as vertical dashed lines
    """
    if quantiles is None or len(quantiles) == 0:
        return
    qs = _quantile(x, quantiles, weights=weights)
    for q in qs:
        ax.axvline(q, lw=2, ls="dashed", color=color)
    if verbose:
        print("Quantiles:")
        print(label, list(zip(quantiles, qs)))


def _quantile_title(x, weights, label, title_quantiles, title_fmt):
    """
Title showing the median of x with the lower/upper errors
    """
    ql, qm, qh = _quantile(x, title_quantiles, weights=weights)
    qm, q_minus, q_plus = [format(q, title_fmt) for q in (qm, qm - ql, qh - qm)]
    return f"{label} = ${{{qm}}}_{{-{q_minus}}}^{{+{q_plus}}}$"


def _corner_figure(fig, npanel):
    """
Create (or reuse) the npanel x npanel grid of axes
with the corner plot layout (from `corner.py`)
    """
    factor = 2.0  # size of side of one panel
    lbdim = 0.5 * factor  # size of left/bottom margin
    trdim = 0.2 * factor  # size of top/right margin
    whspace = 0.05  # size of width/height margin
    plotdim = factor * npanel + factor * (npanel - 1.) * whspace  # plot size
    dim = lbdim + plotdim + trdim  # total size
    fig, axes = _make_subplots(fig, npanel, npanel, dim, dim)
    lb = lbdim / dim
    tr = (lbdim + plotdim) / dim
    fig.subplots_adjust(left=lb,
                        bottom=lb,
                        right=tr,
                        top=tr,
                        wspace=whspace,
                        hspace=whspace)
    return fig, axes


def _hide_panel(ax):
    """
Hide the unused (upper triangle) panel of a corner plot
    """
    ax.set_frame_on(False)
    ax.set_xticks([])
    ax.set_yticks([])


def _setup_corner_panel(ax, max_n_ticks, use_math_text, xlabel, ylabel,
                        label_kwargs):
    """
Set up the ticks and labels of a 2-D panel of a corner plot.
If xlabel (ylabel) is None, the panel is not in the bottom row (left column)
and its x (y) tick labels are hidden.
    """
    for axis in [ax.xaxis, ax.yaxis]:
        axis.set_major_locator(_locator(max_n_ticks, prune="lower"))
        axis.set_major_formatter(_formatter(use_math_text))
    if xlabel is None:
        ax.set_xticklabels([])
    else:
        rotate_ticks(ax, 'x')
        ax.set_xlabel(xlabel, **label_kwargs)
        ax.xaxis.set_label_coords(0.5, -0.3)
    if ylabel is None:
        ax.set_yticklabels([])
    else:
        rotate_ticks(ax, 'y')
        ax.set_ylabel(ylabel, **label_kwargs)
        ax.yaxis.set_label_coords(-0.3, 0.5)


def _rewind_live(samples_u, samples_id, nlive, niter, it):
    """
Reconstruct the nlive live points at iteration it, starting from the
final set of live points stored at the end of samples_u and running
the sampling backwards.
    """
    live_u = np.empty((nlive, samples_u.shape[1]))
    live_u[samples_id[-nlive:]] = samples_u[-nlive:]
    for i in range(1, niter - it + 1):
        r = -(nlive + i)
        live_u[samples_id[r]] = samples_u[r]
    return live_u


def _static_live(results, it, idx):
    """
Live points of a static run at iteration it (or the iteration
at which the dead point idx was proposed)
    """
    # We can only reconstruct the run if the final set of live points
    # were added to the results. This is true by default for dynamic
    # nested sampling runs but not guaranteed for standard runs.
    nlive = results['nlive']
    niter = results['niter']
    if len(results['samples']) - niter != nlive:
        raise ValueError("Cannot reconstruct bound because the "
                         "final set of live points are not included "
                         "in the results.")
    if it is None:
        it = results['samples_it'][idx]
    return _rewind_live(results['samples_u'], results['samples_id'], nlive,
                        niter, it)


def _dynamic_live(results, it, idx):
    """
Live points of the batch of a dynamic run associated with
the iteration it (or the dead point idx)
    """
    batch = results['samples_batch'][idx if it is None else it]
    nbatch = results['batch_nlive'][batch]  # nlive in the batch
    bsel = results['samples_batch'] == batch  # select batch
    niter_eff = sum(bsel) - nbatch  # "effective" iterations in batch
    samples_id = results['samples_id'][bsel]
    samples_id -= min(samples_id)  # re-index to start at zero
    if it is None:
        it = results['samples_it'][idx]
    it_eff = sum(bsel[:it + 1])  # effective iteration in batch
    return _rewind_live(results['samples_u'][bsel], samples_id, nbatch,
                        niter_eff, it_eff)


def _bound_draws(results, it, idx, prior_transform, periodic, reflective,
                 ndraws, show_live):
    """
Draw ndraws points from the bounding distribution used at iteration it
(or used to propose the dead point idx). If show_live is set, also return
the live points at that point (otherwise None). If prior_transform is
provided, the points are transformed to the native model space
(dropping draws outside the unit cube).
    """
    # Check that either `idx` or `it` has been specified.
    if (it is None) == (idx is None):
        raise ValueError("You must specify either an iteration or an index!")

    # Extract bounding distributions.
    try:
        bounds = results['bound']
    except KeyError:
        raise ValueError("No bounds were saved in the results!")
    nsamps = len(results['samples'])

    warn_reflective(reflective)
    check_periodic(bounds[0].ndim, periodic)

    if it is not None:
        if it >= nsamps:
            raise ValueError("The iteration requested goes beyond the "
                             "number of iterations in the run.")
        # Extract bound iterations.
        try:
            bound_iter = np.array(results['bound_iter'])
        except KeyError:
            raise ValueError("Cannot reconstruct the bound used at the "
                             "specified iteration since bound "
                             "iterations were not saved in the results.")
        # Find bound at the specified iteration.
        pidx = 0 if it == 0 else bound_iter[it]
    else:
        if idx >= nsamps:
            raise ValueError("The index requested goes beyond the "
                             "number of samples in the run.")
        try:
            samples_bound = results['samples_bound']
        except KeyError:
            raise ValueError("Cannot reconstruct the bound used to "
                             "compute the specified dead point since "
                             "sample bound indices were not saved "
                             "in the results.")
        pidx = samples_bound[idx]
    bound = bounds[pidx]

    # Reconstruct the live points if we want to show them or if the
    # bound is based on their distribution.
    # (We rewind the run; we could also go forward; this is an
    # arbitrary choice.)
    live_u = None
    if show_live:
        try:
            live_u = _static_live(results, it, idx)
        except Exception:
            # In the dynamic sampling case, we will show the live points used
            # during the batch associated with a particular iteration/bound.
            live_u = _dynamic_live(results, it, idx)
    elif bound.need_centers:
        try:
            live_u = _static_live(results, it, idx)
        except Exception:
            raise ValueError("Live point tracking currently not "
                             "implemented for dynamic sampling results.")

    # Draw samples from the bounding distribution.
    if bound.need_centers:
        bound.ctrs = live_u
    psamps = bound.samples(ndraws, rstate=get_random_generator())

    # Possibly transform to the native model space.
    if prior_transform is not None:
        # Remove points outside of the unit cube.
        sel = [unitcheck(point) for point in psamps]
        psamps = np.array(list(map(prior_transform, psamps[sel])))
        if show_live:
            live_u = np.array(list(map(prior_transform, live_u)))
    return psamps, live_u


def runplot(results,
            span=None,
            logplot=False,
            kde=True,
            nkde=1000,
            color='blue',
            plot_kwargs=None,
            label_kwargs=None,
            lnz_error=True,
            lnz_truth=None,
            truth_color='red',
            truth_kwargs=None,
            max_x_ticks=8,
            max_y_ticks=3,
            use_math_text=True,
            mark_final_live=True,
            fig=None):
    """
    Plot live points, ln(likelihood), ln(weight), and ln(evidence)
    as a function of ln(prior volume).

    Parameters
    ----------
    results : :class:`~dynesty.results.Results` instance
        A :class:`~dynesty.results.Results` instance from a nested
        sampling run.

    span : iterable with shape (4,), optional
        A list where each element is either a length-2 tuple containing
        lower and upper bounds *or* a float `f` from `(0., 1.]`. If a
        float is provided, the bounds are `(f * max(data), max(data))`.
        An example would be::

            span = [(0., 10.), 0.001, 0.2, (5., 6.)]

        Default is `(0., 1.05 * max(data))` for each element.

    logplot : bool, optional
        Whether to plot the evidence on a log scale. Default is `False`.

    kde : bool, optional
        Whether to use kernel density estimation to estimate and plot
        the PDF of the importance weights as a function of log-volume
        (as opposed to the importance weights themselves). Default is
        `True`.

    nkde : int, optional
        The number of grid points used when plotting the kernel density
        estimate. Default is `1000`.

    color : str or iterable with shape (4,), optional
        A `~matplotlib`-style color (either a single color or a different
        value for each subplot) used when plotting the lines in each subplot.
        Default is `'blue'`.

    plot_kwargs : dict, optional
        Extra keyword arguments that will be passed to `plot`.

    label_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_xlabel` and
        `~matplotlib.axes.Axes.set_ylabel` methods.

    lnz_error : bool, optional
        Whether to plot the 1, 2, and 3-sigma approximate error bars
        derived from the ln(evidence) error approximation over the course
        of the run. Default is `True`.

    lnz_truth : float, optional
        A reference value for the evidence that will be overplotted on the
        evidence subplot if provided.

    truth_color : str, optional
        A `~matplotlib`-style color used when plotting :data:`lnz_truth`.
        Default is `'red'`.

    truth_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting
        :data:`lnz_truth`.

    max_x_ticks : int, optional
        Maximum number of ticks allowed for the x axis. Default is `8`.

    max_y_ticks : int, optional
        Maximum number of ticks allowed for the y axis. Default is `3`.

    use_math_text : bool, optional
        Whether the axis tick labels for very large/small exponents should be
        displayed as powers of 10 rather than using `e`. Default is `True`.

    mark_final_live : bool, optional
        Whether to indicate the final addition of recycled live points
        (if they were added to the resulting samples) using
        a dashed vertical line. Default is `True`.

    fig : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`), optional
        If provided, overplot the run onto the provided figure.
        Otherwise, by default an internal figure is generated.

    Returns
    -------
    runplot : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`)
        Output summary plot.

    """

    # Set defaults.
    label_kwargs = label_kwargs or {}
    plot_kwargs = _with_defaults(plot_kwargs, linewidth=5, alpha=0.7)
    truth_kwargs = _with_defaults(truth_kwargs, linestyle='solid', linewidth=3)
    rstate = get_random_generator()

    # Extract results.
    niter = results['niter']  # number of iterations
    logvol = results['logvol']  # ln(prior volume)
    logl = results['logl'] - max(results['logl'])  # ln(normalized likelihood)
    logwt = results['logwt'] - results['logz'][-1]  # ln(importance weight)
    logz = results['logz']  # ln(evidence)
    logzerr = np.array(results['logzerr'])  # error in ln(evidence)
    logzerr[~np.isfinite(logzerr)] = 0.
    nsamps = len(logwt)  # number of samples

    # Check whether the run was "static" or "dynamic".
    try:
        nlive = results['samples_n']
        mark_final_live = False
    except KeyError:
        nlive = np.ones(niter) * results['nlive']
        # Check if the final set of live points were added to the results.
        if nsamps - niter == results['nlive']:
            nlive = np.append(nlive, np.arange(results['nlive'], 0, -1))
        elif mark_final_live:
            warnings.warn("The number of iterations and samples differ "
                          "by an amount that isn't the number of final "
                          "live points. `mark_final_live` has been disabled.")
            mark_final_live = False
    live_idx = niter

    # Determine plotting bounds for each subplot.
    data = [
        nlive,
        np.exp(logl),
        np.exp(logwt), logz if logplot else np.exp(logz)
    ]
    if kde:
        # Derive kernel density estimate.
        wt_kde = gaussian_kde(resample_equal(-logvol, data[2],
                                             rstate=rstate))  # KDE
        logvol_new = np.linspace(logvol[0], logvol[-1], nkde)  # resample
        data[2] = wt_kde.pdf(-logvol_new)  # evaluate KDE PDF
    if span is None:
        span = [(0., 1.05 * max(d)) for d in data]
        no_span = True
    else:
        no_span = False
    span = list(span)
    if len(span) != 4:
        raise ValueError("More bounds provided in `span` than subplots!")
    for i, cur in enumerate(span):
        if np.iterable(cur):
            if len(cur) != 2:
                raise ValueError('Incorrect span value')
        else:
            span[i] = (max(data[i]) * cur, max(data[i]))
    if lnz_error and no_span:
        if logplot:
            # Same lower bound as in ultranest:
            # https://github.com/JohannesBuchner/UltraNest/blob/master/ultranest/plot.py#L139.
            zspan = (logz[-1] - 10.3 * 3. * logzerr[-1],
                     logz[-1] + 1.3 * 3. * logzerr[-1])
        else:
            zspan = (0., 1.05 * np.exp(logz[-1] + 3. * logzerr[-1]))
        span[3] = zspan

    # Setting up default plot layout.
    had_fig = fig or False
    fig, axes = _make_subplots(fig, 4, 1, 16, 16)
    axes = axes.flatten()
    xspan = [ax.get_xlim() for ax in axes]
    if had_fig:
        yspan = [ax.get_ylim() for ax in axes]
    else:
        yspan = span
    # One exception: if the bounds are the plotting default `(0., 1.)`,
    # overwrite them.
    xspan = [t if t != (0., 1.) else (0., -min(logvol)) for t in xspan]
    yspan = [t if t != (0., 1.) else (None, None) for t in yspan]

    # Set up bounds for plotting.
    for i in range(4):
        if xspan[i][0] is None:
            xmin = None
        else:
            xmin = min(0., xspan[i][0])
        if xspan[i][1] is None:
            xmax = -min(logvol)
        else:
            xmax = max(-min(logvol), xspan[i][1])
        if yspan[i][0] is None:
            ymin = None
        else:
            ymin = min(span[i][0], yspan[i][0])
        if yspan[i][1] is None:
            ymax = span[i][1]
        else:
            ymax = max(span[i][1], yspan[i][1])
        axes[i].set_xlim([xmin, xmax])
        axes[i].set_ylim([ymin, ymax])

    # Plotting.
    labels = [
        'Live Points', 'Likelihood\n(normalized)', 'Importance\nWeight',
        'log(Evidence)' if logplot else 'Evidence'
    ]
    if kde:
        labels[2] += ' PDF'

    for i, d in enumerate(data):
        ax = axes[i]
        c = color if isinstance(color, str) else color[i]
        # Setup axes.
        ax.xaxis.set_major_locator(_locator(max_x_ticks))
        ax.yaxis.set_major_locator(_locator(max_y_ticks))
        ax.yaxis.set_major_formatter(_formatter(use_math_text))
        ax.set_xlabel(r"$-\ln X$", **label_kwargs)
        ax.set_ylabel(labels[i], **label_kwargs)
        # Plot run.
        ax.plot(-logvol_new if kde and i == 2 else -logvol,
                d,
                color=c,
                **plot_kwargs)
        if i == 3 and lnz_error:
            if logplot:
                # Same mask as in ultranest:
                # https://github.com/JohannesBuchner/UltraNest/blob/master/ultranest/plot.py#L139
                mask = logz >= ax.get_ylim()[0] - 10
                for s in range(1, 4):
                    ax.fill_between(-logvol[mask], (logz + s * logzerr)[mask],
                                    (logz - s * logzerr)[mask],
                                    color=c,
                                    alpha=0.2)
            else:
                for s in range(1, 4):
                    ax.fill_between(-logvol,
                                    np.exp(logz + s * logzerr),
                                    np.exp(logz - s * logzerr),
                                    color=c,
                                    alpha=0.2)

        # Mark addition of final live points.
        if mark_final_live:
            ax.axvline(-logvol[live_idx],
                       color=c,
                       ls="dashed",
                       lw=2,
                       **plot_kwargs)
            if i == 0:
                ax.axhline(live_idx, color=c, ls="dashed", lw=2, **plot_kwargs)
        # Add truth value(s).
        if i == 3 and lnz_truth is not None:
            ax.axhline(lnz_truth if logplot else np.exp(lnz_truth),
                       color=truth_color,
                       **truth_kwargs)

    return fig, axes


def traceplot(results,
              span=None,
              quantiles=(0.025, 0.5, 0.975),
              smooth=0.02,
              thin=1,
              dims=None,
              post_color='blue',
              post_kwargs=None,
              kde=True,
              nkde=1000,
              trace_cmap='plasma',
              trace_color=None,
              trace_kwargs=None,
              connect=False,
              connect_highlight=10,
              connect_color='red',
              connect_kwargs=None,
              max_n_ticks=5,
              use_math_text=False,
              labels=None,
              label_kwargs=None,
              show_titles=False,
              title_quantiles=(0.025, 0.5, 0.975),
              title_fmt=".2f",
              title_kwargs=None,
              truths=None,
              truth_color='red',
              truth_kwargs=None,
              verbose=False,
              fig=None):
    """
    Plot traces and marginalized posteriors for each parameter.

    Parameters
    ----------
    results : :class:`~dynesty.results.Results` instance
        A :class:`~dynesty.results.Results` instance from a nested
        sampling run.

    span : iterable with shape (ndim,), optional
        A list where each element is either a length-2 tuple containing
        lower and upper bounds or a float from `(0., 1.]` giving the
        fraction of (weighted) samples to include. If a fraction is provided,
        the bounds are chosen to be equal-tailed. An example would be::

            span = [(0., 10.), 0.95, (5., 6.)]

        Default is `0.999999426697` (5-sigma credible interval) for each
        parameter.

    quantiles : iterable, optional
        A list of fractional quantiles to overplot on the 1-D marginalized
        posteriors as vertical dashed lines. Default is `[0.025, 0.5, 0.975]`
        (the 95%/2-sigma credible interval).

    smooth : float or iterable with shape (ndim,), optional
        The standard deviation (either a single value or a different value for
        each subplot) for the Gaussian kernel used to smooth the 1-D
        marginalized posteriors, expressed as a fraction of the span.
        Default is `0.02` (2% smoothing). If an integer is provided instead,
        this will instead default to a simple (weighted) histogram with
        `bins=smooth`.

    thin : int, optional
        Thin the samples so that only each `thin`-th sample is plotted.
        Default is `1` (no thinning).

    dims : iterable of shape (ndim,), optional
        The subset of dimensions that should be plotted. If not provided,
        all dimensions will be shown.

    post_color : str or iterable with shape (ndim,), optional
        A `~matplotlib`-style color (either a single color or a different
        value for each subplot) used when plotting the histograms.
        Default is `'blue'`.

    post_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting the
        marginalized 1-D posteriors.

    kde : bool, optional
        Whether to use kernel density estimation to estimate and plot
        the PDF of the importance weights as a function of log-volume
        (as opposed to the importance weights themselves). Default is
        `True`.

    nkde : int, optional
        The number of grid points used when plotting the kernel density
        estimate. Default is `1000`.

    trace_cmap : str or iterable with shape (ndim,), optional
        A `~matplotlib`-style colormap (either a single colormap or a
        different colormap for each subplot) used when plotting the traces,
        where each point is colored according to its weight. Default is
        `'plasma'`.

    trace_color : str or iterable with shape (ndim,), optional
        A `~matplotlib`-style color (either a single color or a
        different color for each subplot) used when plotting the traces.
        This overrides the `trace_cmap` option by giving all points
        the same color. Default is `None` (not used).

    trace_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting the traces.

    connect : bool, optional
        Whether to draw lines connecting the paths of unique particles.
        Default is `False`.

    connect_highlight : int or iterable, optional
        If `connect=True`, highlights the paths of a specific set of
        particles. If an integer is passed, :data:`connect_highlight`
        random particle paths will be highlighted. If an iterable is passed,
        then the particle paths corresponding to the provided indices
        will be highlighted.

    connect_color : str, optional
        The color of the highlighted particle paths. Default is `'red'`.

    connect_kwargs : dict, optional
        Extra keyword arguments used for plotting particle paths.

    max_n_ticks : int, optional
        Maximum number of ticks allowed. Default is `5`.

    use_math_text : bool, optional
        Whether the axis tick labels for very large/small exponents should be
        displayed as powers of 10 rather than using `e`. Default is `False`.

    labels : iterable with shape (ndim,), optional
        A list of names for each parameter. If not provided, the default name
        used when plotting will follow :math:`x_i` style.

    label_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_xlabel` and
        `~matplotlib.axes.Axes.set_ylabel` methods.

    show_titles : bool, optional
        Whether to display a title above each 1-D marginalized posterior
        showing the 0.5 quantile along with the upper/lower bounds associated
        with the 0.025 and 0.975 (95%/2-sigma credible interval) quantiles.
        Default is `False`.

    title_quantiles : iterable, optional
        A list of fractional quantiles to use in the title. Default is
        `[0.025, 0.5, 0.975]` (median plus 95%/2-sigma credible interval).

    title_fmt : str, optional
        The format string for the quantiles provided in the title. Default is
        `'.2f'`.

    title_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_title` command.

    truths : iterable with shape (ndim,), optional
        A list of reference values that will be overplotted on the traces and
        marginalized 1-D posteriors as solid horizontal/vertical lines.
        Individual values can be exempt using `None`. Default is `None`.

    truth_color : str, optional
        A `~matplotlib`-style color used when plotting `truths`.
        Default is `'red'`.

    truth_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting the vertical
        and horizontal lines with `truths`.

    verbose : bool, optional
        Whether to print the values of the computed quantiles associated with
        each parameter. Default is `False`.

    fig : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`), optional
        If provided, overplot the traces and marginalized 1-D posteriors
        onto the provided figure. Otherwise, by default an
        internal figure is generated.

    Returns
    -------
    traceplot : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`)
        Output trace plot.

    """

    # Set defaults.
    title_kwargs = title_kwargs or {}
    label_kwargs = label_kwargs or {}
    connect_kwargs = _with_defaults(connect_kwargs, alpha=0.7)
    post_kwargs = _with_defaults(post_kwargs, alpha=0.6)
    trace_kwargs = _with_defaults(trace_kwargs,
                                  s=3,
                                  edgecolor=None,
                                  edgecolors=None)
    truth_kwargs = _with_defaults(truth_kwargs, linestyle='solid', linewidth=2)
    rstate = get_random_generator()

    # Extract weighted samples.
    logvol = results['logvol']
    weights = results.importance_weights()
    if kde:
        wts = _kde_weights(logvol, weights, nkde, rstate)
    else:
        wts = weights
    samples = _prepare_samples(results['samples'], weights, dims)
    ndim, nsamps = samples.shape

    # Check ln(volume).
    if logvol.ndim != 1:
        raise ValueError("Ln(volume)'s must be 1-D.")
    if nsamps != logvol.shape[0]:
        raise ValueError("The number of ln(volume)'s and samples disagree!")

    # Check sample IDs.
    if connect:
        if 'samples_id' not in results.keys():
            raise ValueError("Sample IDs are not defined!")
        samples_id = results['samples_id']
        if np.iterable(connect_highlight):
            ids = connect_highlight
        else:
            ids = rstate.choice(np.unique(samples_id),
                                size=connect_highlight,
                                replace=False)

    # Determine plotting bounds for marginalized 1-D posteriors.
    if span is None:
        span = [_SPAN_5SIGMA] * ndim
    span = list(span)
    if len(span) != ndim:
        raise ValueError("Dimension mismatch between samples and span.")
    check_span(span, samples, weights)

    if labels is None:
        labels = [_xlabel(i) for i in range(ndim)]
    if isinstance(smooth, (int, float)):
        smooth = [smooth] * ndim

    # Setting up default plot layout.
    fig, axes = _make_subplots(fig, ndim, 2, 12, 3 * ndim)

    # Plotting.
    for i, x in enumerate(samples):

        # Plot trace.
        ax = axes[i, 0]
        # Set color(s)/colormap(s).
        if trace_color is None:
            color = wts[::thin]
        elif isinstance(trace_color, str):
            color = trace_color
        else:
            color = trace_color[i]
        cmap = trace_cmap if isinstance(trace_cmap, str) else trace_cmap[i]
        # Setup axes.
        ax.set_xlim([0., -min(logvol)])
        ax.set_ylim([min(x), max(x)])
        ax.xaxis.set_major_locator(_locator(max_n_ticks))
        ax.yaxis.set_major_locator(_locator(max_n_ticks))
        ax.yaxis.set_major_formatter(_formatter(use_math_text))
        ax.set_xlabel(r"$-\ln X$", **label_kwargs)
        ax.set_ylabel(labels[i], **label_kwargs)
        # Generate scatter plot.
        ax.scatter(-logvol[::thin],
                   x[::thin],
                   c=color,
                   cmap=cmap,
                   **trace_kwargs)
        if connect:
            # Add lines highlighting specific particle paths.
            for j in ids:
                sel = samples_id[::thin] == j
                ax.plot(-logvol[::thin][sel],
                        x[::thin][sel],
                        color=connect_color,
                        **connect_kwargs)
        # Add truth value(s).
        if truths is not None:
            plot_thruth(ax,
                        truths[i],
                        truth_color,
                        truth_kwargs,
                        horizontal=True)

        # Plot marginalized 1-D posterior.
        ax = axes[i, 1]
        color = post_color if isinstance(post_color, str) else post_color[i]
        # Setup axes
        ax.set_xlim(span[i])
        ax.xaxis.set_major_locator(_locator(max_n_ticks))
        ax.yaxis.set_major_locator(NullLocator())
        ax.xaxis.set_major_formatter(_formatter(use_math_text))
        ax.set_xlabel(labels[i], **label_kwargs)
        # Generate distribution.
        s = smooth[i]
        if isinstance(s, int):
            # If `s` is an integer, plot a weighted histogram with
            # `s` bins within the provided bounds.
            n, b, _ = ax.hist(x,
                              bins=s,
                              weights=weights,
                              color=color,
                              range=np.sort(span[i]),
                              **post_kwargs)
            x0 = np.array(list(zip(b[:-1], b[1:]))).flatten()
            y0 = np.array(list(zip(n, n))).flatten()
        else:
            # If `s` is a float, oversample the data relative to the
            # smoothing filter by a factor of 10, then use a Gaussian
            # filter to smooth the results.
            bins = int(round(10. / s))
            n, b = np.histogram(x,
                                bins=bins,
                                weights=weights,
                                range=np.sort(span[i]))
            n = norm_kde(n, 10.)
            x0 = 0.5 * (b[1:] + b[:-1])
            y0 = n
            ax.fill_between(x0, y0, color=color, **post_kwargs)
        ax.set_ylim([0., max(y0) * 1.05])
        _plot_quantiles(ax, x, weights, quantiles, color, labels[i], verbose)
        # Add truth value(s).
        if truths is not None:
            plot_thruth(ax,
                        truths[i],
                        truth_color,
                        truth_kwargs,
                        vertical=True)
        if show_titles and title_fmt is not None:
            ax.set_title(
                _quantile_title(x, weights, labels[i], title_quantiles,
                                title_fmt), **title_kwargs)

    return fig, axes


def cornerpoints(results,
                 dims=None,
                 thin=1,
                 span=None,
                 cmap='plasma',
                 color=None,
                 kde=True,
                 nkde=1000,
                 plot_kwargs=None,
                 labels=None,
                 label_kwargs=None,
                 truths=None,
                 truth_color='red',
                 truth_kwargs=None,
                 max_n_ticks=5,
                 use_math_text=False,
                 fig=None):
    """
    Generate a (sub-)corner plot of (weighted) samples.

    Parameters
    ----------
    results : :class:`~dynesty.results.Results` instance
        A :class:`~dynesty.results.Results` instance from a nested
        sampling run.

    dims : iterable of shape (ndim,), optional
        The subset of dimensions that should be plotted. If not provided,
        all dimensions will be shown.

    thin : int, optional
        Thin the samples so that only each `thin`-th sample is plotted.
        Default is `1` (no thinning).

    span : iterable with shape (ndim,), optional
        A list where each element is either a length-2 tuple containing
        lower and upper bounds or a float from `(0., 1.]` giving the
        fraction of (weighted) samples to include. If a fraction is provided,
        the bounds are chosen to be equal-tailed. An example would be::

            span = [(0., 10.), 0.95, (5., 6.)]

        Default is `1.` for all parameters (no bound).

    cmap : str, optional
        A `~matplotlib`-style colormap used when plotting the points,
        where each point is colored according to its weight. Default is
        `'plasma'`.

    color : str, optional
        A `~matplotlib`-style color used when plotting the points.
        This overrides the `cmap` option by giving all points
        the same color. Default is `None` (not used).

    kde : bool, optional
        Whether to use kernel density estimation to estimate and plot
        the PDF of the importance weights as a function of log-volume
        (as opposed to the importance weights themselves). Default is
        `True`.

    nkde : int, optional
        The number of grid points used when plotting the kernel density
        estimate. Default is `1000`.

    plot_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting the points.

    labels : iterable with shape (ndim,), optional
        A list of names for each parameter. If not provided, the default name
        used when plotting will follow :math:`x_i` style.

    label_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_xlabel` and
        `~matplotlib.axes.Axes.set_ylabel` methods.

    truths : iterable with shape (ndim,), optional
        A list of reference values that will be overplotted on the traces and
        marginalized 1-D posteriors as solid horizontal/vertical lines.
        Individual values can be exempt using `None`. Default is `None`.

    truth_color : str, optional
        A `~matplotlib`-style color used when plotting `truths`.
        Default is `'red'`.

    truth_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting the vertical
        and horizontal lines with `truths`.

    max_n_ticks : int, optional
        Maximum number of ticks allowed. Default is `5`.

    use_math_text : bool, optional
        Whether the axis tick labels for very large/small exponents should be
        displayed as powers of 10 rather than using `e`. Default is `False`.

    fig : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`), optional
        If provided, overplot the points onto the provided figure object.
        Otherwise, by default an internal figure is generated.

    Returns
    -------
    cornerpoints : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`)
        Output (sub-)corner plot of (weighted) samples.

    """

    # Set defaults.
    label_kwargs = label_kwargs or {}
    plot_kwargs = _with_defaults(plot_kwargs,
                                 s=1,
                                 edgecolor=None,
                                 edgecolors=None)
    truth_kwargs = _with_defaults(truth_kwargs,
                                  linestyle='solid',
                                  linewidth=2,
                                  alpha=0.7)

    # Extract weighted samples.
    logvol = results['logvol']
    weights = results.importance_weights()
    if kde:
        weights = _kde_weights(logvol, weights, nkde, get_random_generator())
    samples = _prepare_samples(results['samples'], weights, dims)
    ndim = samples.shape[0]
    if ndim == 1:
        raise ValueError("cornerpoints does not make sense for 1-D posterior")
    # Determine plotting bounds.
    if span is not None:
        span = list(span)
        if len(span) != ndim:
            raise ValueError("Dimension mismatch between samples and span.")
        check_span(span, samples, weights)

    if labels is None:
        labels = [_xlabel(i) for i in range(ndim)]
    # Color the points by weight if no color is given.
    if color is None:
        color = weights

    fig, axes = _corner_figure(fig, ndim - 1)

    # Plot the 2-D projected samples.
    for i, x in enumerate(samples[1:]):
        for j, y in enumerate(samples[:-1]):
            ax = axes[i, j]
            # Setup axes.
            if span is not None:
                ax.set_xlim(span[j])
                ax.set_ylim(span[i + 1])
            if j > i:
                _hide_panel(ax)
                continue
            _setup_corner_panel(ax, max_n_ticks, use_math_text,
                                labels[j] if i == ndim - 2 else None,
                                labels[i + 1] if j == 0 else None,
                                label_kwargs)
            # Plot distribution.
            in_bounds = np.ones(len(y), dtype=bool)
            if span is not None:
                in_bounds = ((x >= span[i + 1][0]) & (x <= span[i + 1][1]) &
                             (y >= span[j][0]) & (y <= span[j][1]))
            if isinstance(color, str):
                cur_color = color
            else:
                cur_color = color[in_bounds][::thin]
            ax.scatter(y[in_bounds][::thin],
                       x[in_bounds][::thin],
                       c=cur_color,
                       cmap=cmap,
                       **plot_kwargs)
            # Add truth values
            if truths is not None:
                plot_thruth(ax,
                            truths[j],
                            truth_color,
                            truth_kwargs,
                            vertical=True)
                plot_thruth(ax,
                            truths[i + 1],
                            truth_color,
                            truth_kwargs,
                            horizontal=True)

    return (fig, axes)


def cornerplot(results,
               dims=None,
               span=None,
               quantiles=(0.025, 0.5, 0.975),
               color='black',
               smooth=0.02,
               quantiles_2d=None,
               hist_kwargs=None,
               hist2d_kwargs=None,
               labels=None,
               label_kwargs=None,
               show_titles=False,
               title_quantiles=(0.025, 0.5, 0.975),
               title_fmt=".2f",
               title_kwargs=None,
               truths=None,
               truth_color='red',
               truth_kwargs=None,
               max_n_ticks=5,
               top_ticks=False,
               use_math_text=False,
               verbose=False,
               fig=None):
    """
    Generate a corner plot of the 1-D and 2-D marginalized posteriors.

    Parameters
    ----------
    results : :class:`~dynesty.results.Results` instance
        A :class:`~dynesty.results.Results` instance from a nested
        sampling run.

    dims : iterable of shape (ndim,), optional
        The subset of dimensions that should be plotted. If not provided,
        all dimensions will be shown.

    span : iterable with shape (ndim,), optional
        A list where each element is either a length-2 tuple containing
        lower and upper bounds or a float from `(0., 1.]` giving the
        fraction of (weighted) samples to include. If a fraction is provided,
        the bounds are chosen to be equal-tailed. An example would be::

            span = [(0., 10.), 0.95, (5., 6.)]

        Default is `0.999999426697` (5-sigma credible interval).

    quantiles : iterable, optional
        A list of fractional quantiles to overplot on the 1-D marginalized
        posteriors as vertical dashed lines. Default is `[0.025, 0.5, 0.975]`
        (spanning the 95%/2-sigma credible interval).

    color : str, optional
        A `~matplotlib`-style color used when plotting the histograms.
        Default is `'black'`.

    smooth : float or iterable with shape (ndim,), optional
        The standard deviation (either a single value or a different value for
        each subplot) for the Gaussian kernel used to smooth the 1-D and 2-D
        marginalized posteriors, expressed as a fraction of the span.
        Default is `0.02` (2% smoothing). If an integer is provided instead,
        this will instead default to a simple (weighted) histogram with
        `bins=smooth`.

    quantiles_2d : iterable with shape (nquant,), optional
        The quantiles used for plotting the smoothed 2-D distributions.
        If not provided, these default to 0.5, 1, 1.5, and 2-sigma contours
        roughly corresponding to quantiles of `[0.1, 0.4, 0.65, 0.85]`.

    hist_kwargs : dict, optional
        Extra keyword arguments to send to the 1-D (smoothed) histograms.

    hist2d_kwargs : dict, optional
        Extra keyword arguments to send to the 2-D (smoothed) histograms.

    labels : iterable with shape (ndim,), optional
        A list of names for each parameter. If not provided, the default name
        used when plotting will follow :math:`x_i` style.

    label_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_xlabel` and
        `~matplotlib.axes.Axes.set_ylabel` methods.

    show_titles : bool, optional
        Whether to display a title above each 1-D marginalized posterior
        showing the 0.5 quantile along with the upper/lower bounds associated
        with the 0.025 and 0.975 (95%/2-sigma credible interval) quantiles.
        Default is `False`.

    title_quantiles : iterable, optional
        A list of fractional quantiles to use in the title. Default is
        `[0.025, 0.5, 0.975]` (median plus 95%/2-sigma credible interval).

    title_fmt : str or list of str, optional
        The format string or list of strings for the quantiles provided in the title.
        If a list is passed, the length has to match the dimensions. Default is `'.2f'`.

    title_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_title` command.

    truths : iterable with shape (ndim,), optional
        A list of reference values that will be overplotted on the traces and
        marginalized 1-D posteriors as solid horizontal/vertical lines.
        Individual values can be exempt using `None`. Default is `None`.

    truth_color : str, optional
        A `~matplotlib`-style color used when plotting `truths`.
        Default is `'red'`.

    truth_kwargs : dict, optional
        Extra keyword arguments that will be used for plotting the vertical
        and horizontal lines with `truths`.

    max_n_ticks : int, optional
        Maximum number of ticks allowed. Default is `5`.

    top_ticks : bool, optional
        Whether to label the top (rather than bottom) ticks. Default is
        `False`.

    use_math_text : bool, optional
        Whether the axis tick labels for very large/small exponents should be
        displayed as powers of 10 rather than using `e`. Default is `False`.

    verbose : bool, optional
        Whether to print the values of the computed quantiles associated with
        each parameter. Default is `False`.

    fig : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`), optional
        If provided, overplot the traces and marginalized 1-D posteriors
        onto the provided figure. Otherwise, by default an
        internal figure is generated.

    Returns
    -------
    cornerplot : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`)
        Output corner plot.

    """

    # Set defaults.
    title_kwargs = title_kwargs or {}
    label_kwargs = label_kwargs or {}
    hist_kwargs = _with_defaults(hist_kwargs, alpha=0.6)
    hist2d_kwargs = _with_defaults(hist2d_kwargs, levels=quantiles_2d)
    truth_kwargs = _with_defaults(truth_kwargs,
                                  linestyle='solid',
                                  linewidth=2,
                                  alpha=0.7)

    # Extract weighted samples.
    weights = results.importance_weights()
    samples = _prepare_samples(results['samples'], weights, dims)
    ndim = samples.shape[0]

    # Determine plotting bounds.
    if span is None:
        span = [_SPAN_5SIGMA] * ndim
    span = list(span)
    if len(span) != ndim:
        raise ValueError("Dimension mismatch between samples and span.")
    check_span(span, samples, weights)

    if labels is None:
        labels = [_xlabel(i) for i in range(ndim)]
    if isinstance(smooth, (int, float)):
        smooth = [smooth] * ndim
    if isinstance(title_fmt, str):
        title_fmt = [title_fmt] * ndim
    elif title_fmt is not None:
        if len(title_fmt) != ndim:
            raise ValueError("Length of 'title_fmt' needs to match dimensions.")

    fig, axes = _corner_figure(fig, ndim)

    # Plotting.
    for i, x in enumerate(samples):
        ax = axes[i, i]

        # Plot the 1-D marginalized posteriors.

        # Setup axes
        ax.set_xlim(span[i])
        ax.xaxis.set_major_locator(_locator(max_n_ticks, prune="lower"))
        ax.yaxis.set_major_locator(NullLocator())
        ax.xaxis.set_major_formatter(_formatter(use_math_text))
        if i < ndim - 1:
            if top_ticks:
                ax.xaxis.set_ticks_position("top")
                rotate_ticks(ax, 'x')
            else:
                ax.set_xticklabels([])
        else:
            rotate_ticks(ax, 'x')
            ax.set_xlabel(labels[i], **label_kwargs)
            ax.xaxis.set_label_coords(0.5, -0.3)
        # Generate distribution.
        sx = smooth[i]
        if isinstance(sx, int):
            # If `sx` is an integer, plot a weighted histogram with
            # `sx` bins within the provided bounds.
            n, b, _ = ax.hist(x,
                              bins=sx,
                              weights=weights,
                              color=color,
                              range=np.sort(span[i]),
                              **hist_kwargs)
        else:
            # If `sx` is a float, oversample the data relative to the
            # smoothing filter by a factor of 10, then use a Gaussian
            # filter to smooth the results.
            bins = int(round(10. / sx))
            n, b = np.histogram(x,
                                bins=bins,
                                weights=weights,
                                range=np.sort(span[i]))
            n = norm_kde(n, 10.)
            b0 = 0.5 * (b[1:] + b[:-1])
            n, b, _ = ax.hist(b0,
                              bins=b,
                              weights=n,
                              range=np.sort(span[i]),
                              color=color,
                              **hist_kwargs)
        ax.set_ylim([0., max(n) * 1.05])
        _plot_quantiles(ax, x, weights, quantiles, color, labels[i], verbose)
        # Add truth value(s).
        if truths is not None:
            plot_thruth(ax,
                        truths[i],
                        truth_color,
                        truth_kwargs,
                        vertical=True)
        if show_titles and title_fmt is not None:
            ax.set_title(
                _quantile_title(x, weights, labels[i], title_quantiles,
                                title_fmt[i]), **title_kwargs)

        # Plot the 2-D marginalized posteriors.
        for j, y in enumerate(samples):
            ax = axes[i, j]
            if j > i:
                _hide_panel(ax)
                continue
            if j == i:
                continue
            _setup_corner_panel(ax, max_n_ticks, use_math_text,
                                labels[j] if i == ndim - 1 else None,
                                labels[i] if j == 0 else None, label_kwargs)
            # Generate distribution.
            # Only draw contours if one of the dimensions is smoothed.
            sy = smooth[j]
            contours = not (isinstance(sx, int) and isinstance(sy, int))
            _hist2d(y,
                    x,
                    ax=ax,
                    span=[span[j], span[i]],
                    weights=weights,
                    color=color,
                    smooth=[sy, sx],
                    **_with_defaults(hist2d_kwargs,
                                     fill_contours=contours,
                                     plot_contours=contours))
            # Add truth values
            if truths is not None:
                plot_thruth(ax,
                            truths[j],
                            truth_color,
                            truth_kwargs,
                            vertical=True)
                plot_thruth(ax,
                            truths[i],
                            truth_color,
                            truth_kwargs,
                            horizontal=True)

    return (fig, axes)


def boundplot(results,
              dims,
              it=None,
              idx=None,
              prior_transform=None,
              periodic=None,
              reflective=None,
              ndraws=5000,
              color='gray',
              plot_kwargs=None,
              labels=None,
              label_kwargs=None,
              max_n_ticks=5,
              use_math_text=False,
              show_live=False,
              live_color='darkviolet',
              live_kwargs=None,
              span=None,
              fig=None):
    """
    Return the bounding distribution used to propose either (1) live points
    at a given iteration or (2) a specific dead point during
    the course of a run, projected onto the two dimensions specified
    by `dims`.

    Parameters
    ----------
    results : :class:`~dynesty.results.Results` instance
        A :class:`~dynesty.results.Results` instance from a nested
        sampling run.

    dims : length-2 tuple
        The dimensions used to plot the bounding.

    it : int, optional
        If provided, returns the bounding distribution at the specified
        iteration of the nested sampling run. **Note that this option and
        `idx` are mutually exclusive.**

    idx : int, optional
        If provided, returns the bounding distribution used to propose the
        dead point at the specified iteration of the nested sampling run.
        **Note that this option and `it` are mutually exclusive.**

    prior_transform : func, optional
        The function transforming samples within the unit cube back to samples
        in the native model space. If provided, the transformed bounding
        distribution will be plotted in the native model space.

    periodic : iterable, optional
        A list of indices for parameters with periodic boundary conditions.
        Only validated: the saved bounds already wrap these parameters into
        the unit cube. Default is `None`.

    reflective : iterable, optional
        Deprecated and ignored (emits a warning).

    ndraws : int, optional
        The number of random samples to draw from the bounding distribution
        when plotting. Default is `5000`.

    color : str, optional
        The color of the points randomly sampled from the bounding
        distribution. Default is `'gray'`.

    plot_kwargs : dict, optional
        Extra keyword arguments used when plotting the bounding draws.

    labels : iterable with shape (2,), optional
        The names of the two plotted parameters (`dims`), used as the x and
        y axis labels. If not provided, the default name
        used when plotting will follow :math:`x_i` style.

    label_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_xlabel` and
        `~matplotlib.axes.Axes.set_ylabel` methods.

    max_n_ticks : int, optional
        Maximum number of ticks allowed. Default is `5`.

    use_math_text : bool, optional
        Whether the axis tick labels for very large/small exponents should be
        displayed as powers of 10 rather than using `e`. Default is `False`.

    show_live : bool, optional
        Whether the live points at a given iteration (for `it`) or
        associated with the bounding (for `idx`) should be highlighted.
        Default is `False`. In the dynamic case, only the live points
        associated with the batch used to construct the relevant bound
        are plotted.

    live_color : str, optional
        The color of the live points. Default is `'darkviolet'`.

    live_kwargs : dict, optional
        Extra keyword arguments used when plotting the live points.

    span : iterable with shape (2,), optional
        A list where each element is a length-2 tuple containing
        lower and upper bounds. Default is `None` (no bound).

    fig : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`), optional
        If provided, overplot the draws onto the provided figure.
        Otherwise, by default an internal figure is generated.

    Returns
    -------
    bounding_plot : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`)
        Output plot of the bounding distribution.

    """

    # Set defaults.
    label_kwargs = label_kwargs or {}
    plot_kwargs = _with_defaults(plot_kwargs,
                                 marker='o',
                                 linestyle='None',
                                 markersize=1,
                                 alpha=0.4)
    live_kwargs = _with_defaults(live_kwargs,
                                 marker='o',
                                 linestyle='None',
                                 markersize=1)
    if span is not None:
        check_span_pairs(span)

    psamps, lsamps = _bound_draws(results, it, idx, prior_transform, periodic,
                                  reflective, ndraws, show_live)

    # Setting up default plot layout.
    fig, axes = _make_subplots(fig, 1, 1, 6, 6)
    axes = axes[0, 0]

    # Plotting (projecting samples to input dimensions).
    axes.plot(*psamps[:, dims].T, color=color, zorder=1, **plot_kwargs)
    if show_live:
        axes.plot(*lsamps[:, dims].T, color=live_color, zorder=2, **live_kwargs)

    # Setup axes
    if span is not None:
        axes.set_xlim(span[0])
        axes.set_ylim(span[1])
    for axis in [axes.xaxis, axes.yaxis]:
        axis.set_major_locator(_locator(max_n_ticks))
        axis.set_major_formatter(_formatter(use_math_text))
    if labels is None:
        labels = [_xlabel(d) for d in dims]
    axes.set_xlabel(labels[0], **label_kwargs)
    axes.set_ylabel(labels[1], **label_kwargs)

    return fig, axes


def cornerbound(results,
                it=None,
                idx=None,
                dims=None,
                prior_transform=None,
                periodic=None,
                reflective=None,
                ndraws=5000,
                color='gray',
                plot_kwargs=None,
                labels=None,
                label_kwargs=None,
                max_n_ticks=5,
                use_math_text=False,
                show_live=False,
                live_color='darkviolet',
                live_kwargs=None,
                span=None,
                fig=None):
    """
    Return the bounding distribution used to propose either (1) live points
    at a given iteration or (2) a specific dead point during
    the course of a run, projected onto all pairs of dimensions.

    Parameters
    ----------
    results : :class:`~dynesty.results.Results` instance
        A :class:`~dynesty.results.Results` instance from a nested
        sampling run.

    it : int, optional
        If provided, returns the bounding distribution at the specified
        iteration of the nested sampling run. **Note that this option and
        `idx` are mutually exclusive.**

    idx : int, optional
        If provided, returns the bounding distribution used to propose the
        dead point at the specified iteration of the nested sampling run.
        **Note that this option and `it` are mutually exclusive.**

    dims : iterable of shape (ndim,), optional
        The subset of dimensions that should be plotted. If not provided,
        all dimensions will be shown.

    prior_transform : func, optional
        The function transforming samples within the unit cube back to samples
        in the native model space. If provided, the transformed bounding
        distribution will be plotted in the native model space.

    periodic : iterable, optional
        A list of indices for parameters with periodic boundary conditions.
        Only validated: the saved bounds already wrap these parameters into
        the unit cube. Default is `None`.

    reflective : iterable, optional
        Deprecated and ignored (emits a warning).

    ndraws : int, optional
        The number of random samples to draw from the bounding distribution
        when plotting. Default is `5000`.

    color : str, optional
        The color of the points randomly sampled from the bounding
        distribution. Default is `'gray'`.

    plot_kwargs : dict, optional
        Extra keyword arguments used when plotting the bounding draws.

    labels : iterable with shape (ndim,), optional
        A list of names for each parameter. If not provided, the default name
        used when plotting will be in :math:`x_i` style.

    label_kwargs : dict, optional
        Extra keyword arguments that will be sent to the
        `~matplotlib.axes.Axes.set_xlabel` and
        `~matplotlib.axes.Axes.set_ylabel` methods.

    max_n_ticks : int, optional
        Maximum number of ticks allowed. Default is `5`.

    use_math_text : bool, optional
        Whether the axis tick labels for very large/small exponents should be
        displayed as powers of 10 rather than using `e`. Default is `False`.

    show_live : bool, optional
        Whether the live points at a given iteration (for `it`) or
        associated with the bounding (for `idx`) should be highlighted.
        Default is `False`. In the dynamic case, only the live points
        associated with the batch used to construct the relevant bound
        are plotted.

    live_color : str, optional
        The color of the live points. Default is `'darkviolet'`.

    live_kwargs : dict, optional
        Extra keyword arguments used when plotting the live points.

    span : iterable with shape (ndim,), optional
        A list where each element is a length-2 tuple containing
        lower and upper bounds for each dimension. Default is `None`
        (no bound).

    fig : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`), optional
        If provided, overplot the draws onto the provided figure.
        Otherwise, by default an internal figure is generated.


    Returns
    -------
    cornerbound : (`~matplotlib.figure.Figure`, `~matplotlib.axes.Axes`)
        Output corner plot of the bounding distribution.

    """

    # Set defaults.
    label_kwargs = label_kwargs or {}
    plot_kwargs = _with_defaults(plot_kwargs,
                                 marker='o',
                                 linestyle='None',
                                 markersize=1,
                                 alpha=0.4)
    live_kwargs = _with_defaults(live_kwargs,
                                 marker='o',
                                 linestyle='None',
                                 markersize=1)
    if span is not None:
        check_span_pairs(span)
    if results['samples'].shape[1] == 1:
        raise ValueError('cornerbound does not work for 1-D posteriors')

    psamps, lsamps = _bound_draws(results, it, idx, prior_transform, periodic,
                                  reflective, ndraws, show_live)
    # Subsample dimensions.
    if dims is not None:
        psamps = psamps[:, dims]
        if show_live:
            lsamps = lsamps[:, dims]
    ndim = psamps.shape[1]

    if labels is None:
        labels = [_xlabel(i) for i in range(ndim)]

    fig, axes = _corner_figure(fig, ndim - 1)

    # Plot the 2-D projected samples.
    for i in range(ndim - 1):
        for j in range(ndim - 1):
            ax = axes[i, j]
            # Setup axes.
            if span is not None:
                ax.set_xlim(span[j])
                ax.set_ylim(span[i + 1])
            if j > i:
                _hide_panel(ax)
                continue
            _setup_corner_panel(ax, max_n_ticks, use_math_text,
                                labels[j] if i == ndim - 2 else None,
                                labels[i + 1] if j == 0 else None,
                                label_kwargs)
            # Plot distribution.
            ax.plot(psamps[:, j], psamps[:, i + 1], c=color, **plot_kwargs)
            # Add live points.
            if show_live:
                ax.plot(lsamps[:, j],
                        lsamps[:, i + 1],
                        c=live_color,
                        **live_kwargs)

    return (fig, axes)


def _hist2d(x,
            y,
            smooth=0.02,
            span=None,
            weights=None,
            levels=None,
            ax=None,
            color='gray',
            plot_datapoints=False,
            plot_density=True,
            plot_contours=True,
            no_fill_contours=False,
            fill_contours=True,
            contour_kwargs=None,
            contourf_kwargs=None,
            data_kwargs=None):
    """
    Internal function called by :meth:`cornerplot` used to generate a
    a 2-D histogram/contour of samples.

    Parameters
    ----------
    x : iterable with shape (nsamps,)
       Sample positions in the first dimension.

    y : iterable with shape (nsamps,)
       Sample positions in the second dimension.

    smooth : float or iterable with shape (2,), optional
        The standard deviation (either a single value or a different value
        for each dimension) for the Gaussian kernel used to smooth the 2-D
        histogram, expressed as a fraction of the span. If an integer is
        provided instead, a simple (weighted) histogram with `bins=smooth`
        is used. Default is `0.02` (2% smoothing).

    span : iterable with shape (2,), optional
        A list where each element (for `x` and `y`) is either a length-2
        tuple containing lower and upper bounds or a float from `(0., 1.]`
        giving the fraction of (weighted) samples to include. If a fraction
        is provided, the bounds are chosen to be equal-tailed. An example
        would be::

            span = [(0., 10.), 0.95]

        Default is `0.999999426697` (5-sigma credible interval).

    weights : iterable with shape (nsamps,)
        Weights associated with the samples. Default is `None` (no weights).

    levels : iterable, optional
        The contour levels to draw. Default are `[0.5, 1, 1.5, 2]`-sigma.

    ax : `~matplotlib.axes.Axes`, optional
        An `~matplotlib.axes.axes` instance on which to add the 2-D histogram.
        If not provided, a figure will be generated.

    color : str, optional
        The `~matplotlib`-style color used to draw lines and color cells
        and contours. Default is `'gray'`.

    plot_datapoints : bool, optional
        Whether to plot the individual data points. Default is `False`.

    plot_density : bool, optional
        Whether to draw the density colormap. Default is `True`.

    plot_contours : bool, optional
        Whether to draw the contours. Default is `True`.

    no_fill_contours : bool, optional
        Whether to add absolutely no filling to the contours. This differs
        from `fill_contours=False`, which still adds a white fill at the
        densest points. Default is `False`.

    fill_contours : bool, optional
        Whether to fill the contours. Default is `True`.

    contour_kwargs : dict
        Any additional keyword arguments to pass to the `contour` method.

    contourf_kwargs : dict
        Any additional keyword arguments to pass to the `contourf` method.

    data_kwargs : dict
        Any additional keyword arguments to pass to the `plot` method when
        adding the individual data points.

    """

    if ax is None:
        ax = pl.gca()

    # Determine plotting bounds.
    data = [x, y]
    if span is None:
        span = [_SPAN_5SIGMA] * 2
    span = list(span)
    if len(span) != 2:
        raise ValueError("Dimension mismatch between samples and span.")
    check_span(span, data, weights)

    # The default "sigma" contour levels.
    if levels is None:
        levels = 1.0 - np.exp(-0.5 * np.arange(0.5, 2.1, 0.5)**2)

    # Color map for the density plot, over-plotted to indicate the
    # density of the points near the center.
    density_cmap = LinearSegmentedColormap.from_list("density_cmap",
                                                     [color, (1, 1, 1, 0)])

    # Color map used to hide the points at the high density areas.
    white_cmap = LinearSegmentedColormap.from_list("white_cmap", [(1, 1, 1),
                                                                  (1, 1, 1)],
                                                   N=2)

    # This "color map" is the list of colors for the contour levels if the
    # contours are filled.
    rgba_color = colorConverter.to_rgba(color)
    n_levels = len(levels)
    contour_cmap = [list(rgba_color)] * n_levels + [rgba_color]
    for i in range(n_levels):
        contour_cmap[i][-1] *= float(i) / (n_levels + 1)

    # Initialize smoothing.
    # If `s` is an integer, the weighted histogram has `s` bins within the
    # provided bounds and is not smoothed. If `s` is a float, oversample
    # the data relative to the smoothing filter by a factor of 2, then use
    # a Gaussian filter to smooth the results.
    if isinstance(smooth, (int, float)):
        smooth = [smooth, smooth]
    bins = [s if isinstance(s, int) else int(round(2. / s)) for s in smooth]
    svalues = [0. if isinstance(s, int) else 2. for s in smooth]

    # We'll make the 2D histogram to directly estimate the density.
    try:
        H, X, Y = np.histogram2d(x.flatten(),
                                 y.flatten(),
                                 bins=bins,
                                 range=list(map(np.sort, span)),
                                 weights=weights)
    except ValueError:
        raise ValueError("It looks like at least one of your sample columns "
                         "have no dynamic range.")

    # Smooth the results (a zero sigma leaves that axis unsmoothed).
    H = norm_kde(H, svalues)

    # Compute the density levels.
    Hflat = H.flatten()
    inds = np.argsort(Hflat)[::-1]
    Hflat = Hflat[inds]
    sm = np.cumsum(Hflat)
    sm /= sm[-1]
    V = np.empty(len(levels))
    for i, v0 in enumerate(levels):
        try:
            V[i] = Hflat[sm <= v0][-1]
        except Exception:
            V[i] = Hflat[0]
    V.sort()
    m = np.diff(V) == 0
    if np.any(m) and plot_contours:
        logging.warning("Too few points to create valid contours.")
    if np.all(m):
        logging.warning('No points at all in the plotted region')
    else:
        while np.any(m):
            V[np.where(m)[0][0]] *= 1.0 - 1e-4
            m = np.diff(V) == 0
        V.sort()

    # Compute the bin centers.
    X1, Y1 = 0.5 * (X[1:] + X[:-1]), 0.5 * (Y[1:] + Y[:-1])

    # Extend the array for the sake of the contours at the plot edges:
    # repeat the edge values once, then pad with the minimum.
    H2 = np.pad(np.pad(H, 1, mode='edge'), 1, constant_values=H.min())
    X2 = np.concatenate([
        X1[0] + np.array([-2, -1]) * np.diff(X1[:2]), X1,
        X1[-1] + np.array([1, 2]) * np.diff(X1[-2:])
    ])
    Y2 = np.concatenate([
        Y1[0] + np.array([-2, -1]) * np.diff(Y1[:2]), Y1,
        Y1[-1] + np.array([1, 2]) * np.diff(Y1[-2:])
    ])

    # Plot the data points.
    if plot_datapoints:
        data_kwargs = _with_defaults(data_kwargs,
                                     color=color,
                                     ms=2.0,
                                     mec="none",
                                     alpha=0.1)
        ax.plot(x, y, "o", zorder=-1, rasterized=True, **data_kwargs)

    # Plot the base fill to hide the densest data points.
    if (plot_contours or plot_density) and not no_fill_contours:
        ax.contourf(X2,
                    Y2,
                    H2.T, [V.min(), H.max()],
                    cmap=white_cmap,
                    antialiased=False)

    if plot_contours and fill_contours:
        contourf_kwargs = _with_defaults(contourf_kwargs,
                                         colors=contour_cmap,
                                         antialiased=False)
        ax.contourf(X2, Y2, H2.T,
                    np.concatenate([[0], V, [H.max() * (1 + 1e-4)]]),
                    **contourf_kwargs)

    # Plot the density map. This can't be plotted at the same time as the
    # contour fills.
    elif plot_density:
        ax.pcolor(X, Y, H.max() - H.T, cmap=density_cmap)

    # Plot the contour edge colors.
    if plot_contours:
        contour_kwargs = _with_defaults(contour_kwargs, colors=color)
        ax.contour(X2, Y2, H2.T, V, **contour_kwargs)

    ax.set_xlim(span[0])
    ax.set_ylim(span[1])
